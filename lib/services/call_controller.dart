import 'dart:async';
import 'package:flutter/foundation.dart';
import 'package:flutter_webrtc/flutter_webrtc.dart';
import 'signaling_service.dart';
import '../webrtc_service.dart';

/// Single unified call state model.
enum CallState {
  idle,
  calling,
  ringing,
  connecting,
  connected,
  ended,
}

/// Central controller and single owner of active call state and WebRTC lifecycle.
class CallController extends ChangeNotifier {
  final SignalingService signalingService;
  final WebRTCService webrtcService;

  CallState _state = CallState.idle;
  String? _currentCallId;
  String? _otherUserId;
  String? _otherUserName;
  String? _lastFailureReason;
  DateTime? _callStartTime;
  StreamSubscription<Map<String, dynamic>>? _signalingSub;

  CallController({
    required this.signalingService,
    required this.webrtcService,
  }) {
    _initListeners();
  }

  CallState get state => _state;
  String? get currentCallId => _currentCallId;
  String? get otherUserId => _otherUserId;
  String? get otherUserName => _otherUserName;
  String? get lastFailureReason => _lastFailureReason;
  DateTime? get callStartTime => _callStartTime;

  bool get isMuted => webrtcService.isMuted;
  bool get isSpeakerOn => webrtcService.isSpeakerOn;

  void _initListeners() {
    // Listen to incoming signaling messages
    _signalingSub?.cancel();
    _signalingSub = signalingService.messageStream.listen(_handleSignalingMessage);

    // Listen to local WebRTC candidates generated by flutter_webrtc
    webrtcService.onLocalCandidate = (candidate) {
      if (_currentCallId != null && _otherUserId != null) {
        debugPrint('[CallController SEND] ice_candidate for call $_currentCallId');
        signalingService.send({
          'type': 'ice_candidate',
          'call_id': _currentCallId,
          'to_user_id': _otherUserId,
          'candidate': {
            'candidate': candidate.candidate,
            'sdpMid': candidate.sdpMid,
            'sdpMLineIndex': candidate.sdpMLineIndex,
          },
        });
      }
    };

    // Listen to WebRTC connection state changes
    webrtcService.onConnectionState = (connState) {
      debugPrint('[CallController] WebRTC connection state -> $connState');
      if (connState == RTCPeerConnectionState.RTCPeerConnectionStateConnected) {
        _callStartTime = DateTime.now();
        _setState(CallState.connected);
      } else if (connState == RTCPeerConnectionState.RTCPeerConnectionStateFailed ||
          connState == RTCPeerConnectionState.RTCPeerConnectionStateDisconnected) {
        if (_state == CallState.connected || _state == CallState.connecting) {
          debugPrint('[CallController] WebRTC disconnected, ending call cleanly.');
          endCall();
        }
      }
    };

    // If signaling drops during an active call, cleanly tear down
    signalingService.addListener(_handleSignalingConnectionChange);
  }

  void _handleSignalingConnectionChange() {
    if (!signalingService.isConnected &&
        (_state != CallState.idle && _state != CallState.ended)) {
      debugPrint('[CallController] Signaling socket lost during active call. Cleaning up.');
      _lastFailureReason = 'Signaling disconnected';
      endCall();
    }
  }

  void _setState(CallState newState) {
    if (_state != newState) {
      debugPrint('[CallController STATE] $_state -> $newState');
      _state = newState;
      notifyListeners();
    }
  }

  /// Initiates an outgoing call to [targetUserId].
  /// Sends `call_request` with NO local call_id (backend generates authoritative call_id).
  void startCall(String targetUserId, String targetUserName) {
    if (!signalingService.isConnected) {
      _lastFailureReason = 'Not connected to server';
      _setState(CallState.ended);
      return;
    }

    if (_state != CallState.idle && _state != CallState.ended) {
      debugPrint('[CallController] Already in call (state: $_state). Resetting first.');
      resetCallState();
    }

    _otherUserId = targetUserId.trim();
    _otherUserName = targetUserName.trim();
    _currentCallId = null; // Awaiting backend authoritative call_id
    _lastFailureReason = null;
    _callStartTime = null;

    _setState(CallState.calling);

    debugPrint('[CallController] Sending call_request to $_otherUserId...');
    signalingService.send({
      'type': 'call_request',
      'to_user_id': _otherUserId,
    });
  }

  /// Accepts an incoming call.
  /// Sends `call_accepted` using the backend's authoritative [currentCallId],
  /// transitions to [CallState.connecting], initializes WebRTC, and awaits remote offer.
  Future<void> acceptCall() async {
    if (_currentCallId == null || _otherUserId == null) {
      debugPrint('[CallController ERROR] Cannot accept call: missing call_id or caller');
      return;
    }

    debugPrint('[CallController] Accepting call $_currentCallId from $_otherUserId...');
    signalingService.send({
      'type': 'call_accepted',
      'call_id': _currentCallId,
      'to_user_id': _otherUserId,
    });

    _setState(CallState.connecting);

    try {
      await webrtcService.initializePeerConnection();
    } catch (e) {
      debugPrint('[CallController ERROR] Error initializing WebRTC on accept: $e');
      endCall();
    }
  }

  /// Rejects an incoming call.
  void rejectCall() {
    if (_currentCallId != null && _otherUserId != null) {
      debugPrint('[CallController] Rejecting call $_currentCallId from $_otherUserId...');
      signalingService.send({
        'type': 'call_rejected',
        'call_id': _currentCallId,
        'to_user_id': _otherUserId,
      });
    }
    _cleanupSession();
    _setState(CallState.idle);
  }

  /// Ends an active or pending call cleanly.
  Future<void> endCall() async {
    if (_currentCallId != null && _otherUserId != null) {
      debugPrint('[CallController] Ending call $_currentCallId with $_otherUserId...');
      signalingService.send({
        'type': 'call_ended',
        'call_id': _currentCallId,
        'to_user_id': _otherUserId,
      });
    }

    await webrtcService.endCall();
    _cleanupSession();
    _setState(CallState.idle);
  }

  /// Resets call state to idle without sending redundant messages.
  void resetCallState() {
    if (_currentCallId != null && _otherUserId != null) {
      signalingService.send({
        'type': 'call_ended',
        'call_id': _currentCallId,
        'to_user_id': _otherUserId,
      });
    }
    webrtcService.endCall();
    _cleanupSession();
    _setState(CallState.idle);
  }

  void _cleanupSession() {
    _currentCallId = null;
    _otherUserId = null;
    _otherUserName = null;
    _callStartTime = null;
  }

  void toggleMute() {
    webrtcService.toggleMute();
    notifyListeners();
  }

  Future<void> setSpeaker(bool enabled) async {
    await webrtcService.setSpeaker(enabled);
    notifyListeners();
  }

  Future<void> _handleSignalingMessage(Map<String, dynamic> data) async {
    final String? type = data['type'] as String?;
    if (type == null) return;

    debugPrint('[CallController RECV]: type=$type');

    switch (type) {
      case 'incoming_call':
        // Receiver receives incoming call from backend
        final callId = (data['call_id'] ?? '').toString();
        final fromUserId = (data['from_user_id'] ?? data['caller_id'] ?? '').toString();
        final callerName = (data['caller_name'] ??
                data['callerName'] ??
                data['from_name'] ??
                fromUserId)
            .toString();

        _currentCallId = callId;
        _otherUserId = fromUserId;
        _otherUserName = callerName;
        _lastFailureReason = null;
        _callStartTime = null;

        _setState(CallState.ringing);
        break;

      case 'call_accepted':
        // Caller receives call_accepted containing authoritative call_id
        final callId = (data['call_id'] ?? _currentCallId ?? '').toString();
        if (callId.isNotEmpty) {
          _currentCallId = callId;
        }

        _setState(CallState.connecting);

        // As Caller: initialize WebRTC, create SDP offer, and send it
        try {
          await webrtcService.initializePeerConnection();
          final offerSdp = await webrtcService.createOffer();
          debugPrint('[CallController SEND] offer for call $_currentCallId');
          signalingService.send({
            'type': 'offer',
            'call_id': _currentCallId,
            'to_user_id': _otherUserId,
            'sdp': offerSdp,
          });
        } catch (e) {
          debugPrint('[CallController ERROR] Error creating offer: $e');
          endCall();
        }
        break;

      case 'call_rejected':
        _lastFailureReason = 'Call was rejected';
        await webrtcService.endCall();
        _cleanupSession();
        _setState(CallState.ended);
        break;

      case 'call_failed':
        final reason = (data['reason'] ?? 'call_failed').toString();
        _lastFailureReason = (reason == 'offline')
            ? 'User is offline'
            : (reason == 'busy')
                ? 'User is busy'
                : reason;
        await webrtcService.endCall();
        _cleanupSession();
        _setState(CallState.ended);
        break;

      case 'call_ended':
        _lastFailureReason = data['reason']?.toString() ?? 'Call ended by remote peer';
        await webrtcService.endCall();
        _cleanupSession();
        _setState(CallState.ended);
        break;

      case 'offer':
        // Receiver handles SDP offer and creates SDP answer
        final String sdp = (data['sdp'] ?? data['description']?['sdp']) as String;
        try {
          if (webrtcService.peerConnection == null) {
            await webrtcService.initializePeerConnection();
          }
          final answerSdp = await webrtcService.handleOfferAndCreateAnswer(sdp);
          debugPrint('[CallController SEND] answer for call $_currentCallId');
          signalingService.send({
            'type': 'answer',
            'call_id': _currentCallId,
            'to_user_id': _otherUserId,
            'sdp': answerSdp,
          });
        } catch (e) {
          debugPrint('[CallController ERROR] Error handling offer: $e');
        }
        break;

      case 'answer':
        // Caller handles SDP answer
        final String sdp = (data['sdp'] ?? data['description']?['sdp']) as String;
        try {
          await webrtcService.handleAnswer(sdp);
        } catch (e) {
          debugPrint('[CallController ERROR] Error handling answer: $e');
        }
        break;

      case 'ice_candidate':
      case 'ice-candidate':
        // Remote ICE candidate received
        final dynamic candPayload = data['candidate'];
        if (candPayload is Map) {
          final candidateStr = candPayload['candidate'] as String?;
          final sdpMid = candPayload['sdpMid'] as String?;
          final sdpMLineIndex = candPayload['sdpMLineIndex'] as int?;
          if (candidateStr != null && candidateStr.isNotEmpty) {
            await webrtcService.addRemoteCandidate(
              RTCIceCandidate(candidateStr, sdpMid, sdpMLineIndex),
            );
          }
        } else if (candPayload is String && candPayload.isNotEmpty) {
          await webrtcService.addRemoteCandidate(
            RTCIceCandidate(
              candPayload,
              data['sdpMid'] as String?,
              data['sdpMLineIndex'] as int?,
            ),
          );
        }
        break;

      default:
        break;
    }
  }

  bool _isDisposed = false;

  @override
  void notifyListeners() {
    if (!_isDisposed) {
      super.notifyListeners();
    }
  }

  @override
  void dispose() {
    _isDisposed = true;
    signalingService.removeListener(_handleSignalingConnectionChange);
    _signalingSub?.cancel();
    super.dispose();
  }
}
